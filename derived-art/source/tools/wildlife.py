"""The overworld's wildlife sheets (the user's, November 2026: small life in the world), from human-drawn
LPC art in tools/wildlife-sources (credits there and in client/CREDITS.txt): each sheet laid out alike for
client/src/world/Wildlife.js, a row per way it faces (down, left, right, up), its walk rows then its
flight rows, and client/src/world/wildlife-sheets.js saying how big a frame is and how many a row holds.

    python tools/wildlife.py
"""
import json
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'wildlife-sources')
OUT = os.path.join(HERE, '..', 'client', 'assets', 'world', 'wildlife')
WAYS = ('down', 'left', 'right', 'up')

# kind: (source, cell w, cell h, frames a row, {way: source row} walking, {way: source row} flying,
#        source column the kind starts at, crop (w, h) of each cell from its top left, or None)
KINDS = {
    # Reemax's seagull and raven (art by Tuomo Untinen): flight only, the bird in the top half of a 32 x 64 cell
    'gull': ('reemax-raven-seagull.png', 32, 64, 3, None, {'down': 0, 'left': 1, 'right': 2, 'up': 3}, 0, (32, 32)),
    'raven': ('reemax-raven-seagull.png', 32, 64, 3, None, {'down': 0, 'left': 1, 'right': 2, 'up': 3}, 3, (32, 32)),
    # bluecarrot16's birds: flying rows 0-3 (left, up, down, right), walking rows 4-7 (left, up, down, right)
    'shorebird': ('bluecarrot16-bird_2_white.png', 32, 32, 3, {'down': 6, 'left': 4, 'right': 7, 'up': 5},
                  {'down': 2, 'left': 0, 'right': 3, 'up': 1}, 0, None),
    'crow': ('bluecarrot16-bird_2_black.png', 32, 32, 3, {'down': 6, 'left': 4, 'right': 7, 'up': 5},
             {'down': 2, 'left': 0, 'right': 3, 'up': 1}, 0, None),
    'sparrow': ('bluecarrot16-bird_3_sparrow.png', 32, 32, 3, {'down': 6, 'left': 4, 'right': 7, 'up': 5},
                {'down': 2, 'left': 0, 'right': 3, 'up': 1}, 0, None),
    # tapatilorenzo's foxes (64 x 64: down, right, left, up) and deer (64 x 96: down, left, right, up), walking
    'fox': ('tapatilorenzo-fox-woods.png', 64, 64, 4, {'down': 0, 'left': 2, 'right': 1, 'up': 3}, None, 0, None),
    'arcticfox': ('tapatilorenzo-fox-arctic.png', 64, 64, 4, {'down': 0, 'left': 2, 'right': 1, 'up': 3}, None, 0, None),
    'doe': ('tapatilorenzo-deer-light-doe.png', 64, 96, 4, {'down': 0, 'left': 1, 'right': 2, 'up': 3}, None, 0, None),
    'buck': ('tapatilorenzo-deer-light-buck.png', 64, 96, 4, {'down': 0, 'left': 1, 'right': 2, 'up': 3}, None, 0, None),
}


def build():
    os.makedirs(OUT, exist_ok=True)
    meta = {}
    for kind, (src, cw, ch, n, walk, fly, col0, crop) in KINDS.items():
        im = Image.open(os.path.join(SRC, src)).convert('RGBA')
        fw, fh = crop or (cw, ch)
        rows = [r for rows in (walk, fly) if rows for r in (rows[w] for w in WAYS)]
        sheet = Image.new('RGBA', (fw * n, fh * len(rows)), (0, 0, 0, 0))
        for i, r in enumerate(rows):
            for f in range(n):
                x, y = (col0 + f) * cw, r * ch
                sheet.alpha_composite(im.crop((x, y, x + fw, y + fh)), (f * fw, i * fh))
        sheet.save(os.path.join(OUT, f'{kind}.png'), optimize=True)
        meta[kind] = {'w': fw, 'h': fh, 'frames': n, 'walk': bool(walk), 'fly': bool(fly)}
        print(kind, sheet.size)
    js = os.path.join(HERE, '..', 'client', 'src', 'world', 'wildlife-sheets.js')
    with open(js, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/wildlife.py; do not edit. Each sheet: a frame w x h, `frames` a row, a row per way it\n'
                '// faces (down, left, right, up), its walk rows (if `walk`) then its flight rows (if `fly`).\n')
        f.write('export const SHEETS = ' + json.dumps(meta, indent=1) + ';\n')


if __name__ == '__main__':
    build()
